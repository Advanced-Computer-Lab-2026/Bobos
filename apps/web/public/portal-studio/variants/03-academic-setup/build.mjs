import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const dir=path.dirname(fileURLToPath(import.meta.url));
const files=['config','seed','domain','ui','records','forms','details','controller','register'];
const sources=await Promise.all(files.map(async name=>`\n/* ===== src/${name}.js ===== */\n`+(await readFile(path.join(dir,'src',name+'.js'),'utf8')).replace(/^import .*;\s*$/gm,'').replace(/^export /gm,'')));
await writeFile(path.join(dir,'pages.js'),'/* Portal · Academic setup. Generated by node build.mjs. No external dependencies. */\n(()=>{\n\'use strict\';\n'+sources.join('\n')+'\n})();\n');
console.log('Built pages.js: eight page registrations, ten choices each.');
